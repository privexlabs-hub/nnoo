/** Extracts the custom properties declared in the first `:root { … }` block. */
export function parseRootTokens(css: string): Record<string, string> {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const root = /:root\s*\{([\s\S]*?)\n\}/.exec(withoutComments);
  if (!root?.[1]) throw new Error('no :root block found');
  const tokens: Record<string, string> = {};
  for (const m of root[1].matchAll(/(--[a-z0-9-]+)\s*:\s*([^;]+);/gi)) {
    tokens[m[1]!] = m[2]!.trim().replace(/\s+/g, ' ');
  }
  return tokens;
}

export function renderTokensModule(tokens: Record<string, string>): string {
  const body = Object.entries(tokens)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join('\n');
  return `// GENERATED by scripts/generate.ts from tokens.css — do not edit by hand.
export const tokens = {
${body}
} as const;

export type TokenName = keyof typeof tokens;

/** Raw value of a token. Values may reference other tokens via var(--x); use resolveToken for a literal. */
export const token = (name: TokenName): string => tokens[name];

/** Resolves var(--x) chains to a literal value (for React Native, which has no CSS variables). */
export function resolveToken(name: TokenName, depth = 0): string {
  const value: string = tokens[name];
  const ref = /^var\\((--[a-z0-9-]+)\\)$/i.exec(value);
  if (!ref || depth > 10) return value;
  return ref[1]! in tokens ? resolveToken(ref[1] as TokenName, depth + 1) : value;
}
`;
}
